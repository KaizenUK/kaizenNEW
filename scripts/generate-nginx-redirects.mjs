import fs from "node:fs/promises";
import path from "node:path";
import { createClient } from "@sanity/client";

const OUTPUT_FILE = path.resolve("dist/redirects.generated.conf");
const API_VERSION = "2025-01-01";

function getEnv(key) {
  return String(process.env[key] ?? "").trim();
}

function getSanityConfig() {
  const projectId =
    getEnv("PUBLIC_SANITY_PROJECT_ID") || getEnv("SANITY_PROJECT_ID");
  const dataset = getEnv("PUBLIC_SANITY_DATASET") || getEnv("SANITY_DATASET");
  const token = getEnv("SANITY_API_TOKEN");

  if (!projectId || !dataset) {
    return null;
  }

  return { projectId, dataset, token };
}

function escapeNginx(value) {
  return String(value).replace(/"/g, '\\"');
}

function normalizePathname(value) {
  const raw = String(value ?? "").trim();
  if (!raw) return "";
  if (raw.startsWith("http://") || raw.startsWith("https://")) return "";
  if (!raw.startsWith("/")) return `/${raw}`;
  return raw;
}

function buildRedirectRule(entry) {
  const source = normalizePathname(entry?.source);
  const destination = normalizePathname(entry?.destination);
  const isPermanent = Boolean(entry?.isPermanent);

  if (!source || !destination || source === destination) {
    return null;
  }

  const status = isPermanent ? 301 : 302;
  return `location = ${escapeNginx(source)} { return ${status} ${escapeNginx(destination)}; }`;
}

async function writeFile(content) {
  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, content, "utf8");
}

async function main() {
  const sanityConfig = getSanityConfig();

  if (!sanityConfig) {
    await writeFile(
      [
        "# Auto-generated by scripts/generate-nginx-redirects.mjs",
        "# No Sanity configuration found. No redirects generated.",
        "",
      ].join("\n"),
    );
    console.log("No Sanity env found. Wrote empty redirects include.");
    return;
  }

  const client = createClient({
    ...sanityConfig,
    apiVersion: API_VERSION,
    useCdn: false,
    perspective: "published",
  });

  const query = `*[_type == "redirect"]{source,destination,isPermanent}`;
  const redirects = await client.fetch(query);

  const rules = (Array.isArray(redirects) ? redirects : [])
    .map(buildRedirectRule)
    .filter(Boolean);

  const content = [
    "# Auto-generated by scripts/generate-nginx-redirects.mjs",
    "# Include this file inside your server block.",
    ...rules,
    "",
  ].join("\n");

  await writeFile(content);
  console.log(`Generated ${rules.length} redirect rule(s) at ${OUTPUT_FILE}`);
}

main().catch(async (error) => {
  console.error("Failed to generate redirects:", error);
  await writeFile(
    [
      "# Auto-generated by scripts/generate-nginx-redirects.mjs",
      "# Redirect generation failed.",
      "",
    ].join("\n"),
  );
  process.exitCode = 1;
});
