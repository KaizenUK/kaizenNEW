function expressPlugin(): Plugin {
  return {
    name: "express-plugin",
    apply: "serve",
    configureServer(server) {
      const app = createServer();
      server.middlewares.use(app);
    },
  };
}

function nonBlockingStylesPlugin(): Plugin {
  return {
    name: "non-blocking-styles-plugin",
    apply: "build",
    transformIndexHtml(html) {
      return html.replace(
        /<link rel="stylesheet"([^>]*href="(\/assets\/[^"]+\.css)"[^>]*)>/g,
        (_full, attrs: string, href: string) => {
          const hasCrossorigin = /\bcrossorigin\b/.test(attrs);
          const crossoriginAttr = hasCrossorigin ? " crossorigin" : "";
          return [
            `<link rel="preload" as="style" href="${href}"${crossoriginAttr} onload="this.onload=null;this.rel='stylesheet'">`,
            `<noscript><link rel="stylesheet" href="${href}"${crossoriginAttr}></noscript>`,
          ].join("\n    ");
        },
      );
    },
  };
}
